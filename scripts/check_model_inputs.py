#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from common import read_jsonl


FORBIDDEN_KEYS = {
    "sample_id",
    "task_type",
    "environment_type",
    "expected_decision",
    "gold_rationale",
    "hidden_metadata",
    "authorization_ref",
    "metadata_ref",
    "sample_ref",
}

LABEL_TOKEN_RE = re.compile(r"(^|[^a-z0-9])(allow|deny|ask|defer|fallback)([^a-z0-9]|$)", re.IGNORECASE)
OPAQUE_INPUT_ID_RE = re.compile(r"^[a-z][a-z0-9_]*_[a-f0-9]{12}$")


def default_id_map_path(inputs: Path) -> Path:
    return inputs.with_name(f"{inputs.stem}.id_map.json")


def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def load_id_map(path: Path) -> list[dict[str, str]]:
    obj = read_json(path)
    if not isinstance(obj, dict) or not isinstance(obj.get("records"), list):
        raise ValueError(f"{path}: expected input id map with a records list")

    records: list[dict[str, str]] = []
    for index, record in enumerate(obj["records"], start=1):
        if not isinstance(record, dict):
            raise ValueError(f"{path}: records[{index}] must be an object")
        input_id = record.get("input_id")
        sample_id = record.get("sample_id")
        if not isinstance(input_id, str) or not isinstance(sample_id, str):
            raise ValueError(f"{path}: records[{index}] requires string input_id and sample_id")
        records.append({"input_id": input_id, "sample_id": sample_id})
    return records


def walk_forbidden(obj: Any, path: str, errors: list[str]) -> None:
    if isinstance(obj, dict):
        for key, value in obj.items():
            current_path = f"{path}.{key}" if path else key
            if key in FORBIDDEN_KEYS:
                errors.append(f"forbidden key {key!r} at {current_path}")
            walk_forbidden(value, current_path, errors)
    elif isinstance(obj, list):
        for index, value in enumerate(obj):
            walk_forbidden(value, f"{path}[{index}]", errors)


def check_public_input_id(row: dict[str, Any], errors: list[str]) -> None:
    input_id = row.get("input_id")
    label = input_id if isinstance(input_id, str) else f"line_{row.get('_line_no', '?')}"
    if not isinstance(input_id, str):
        errors.append(f"{label}: model input requires string input_id")
        return
    if not OPAQUE_INPUT_ID_RE.match(input_id):
        errors.append(f"{input_id}: input_id must be opaque and hash-suffixed, e.g. asb_v0_3e9302b45d99")
    if LABEL_TOKEN_RE.search(input_id):
        errors.append(f"{input_id}: input_id contains a decision label token")


def check_id_map(
    rows: list[dict[str, Any]],
    gold_path: Path | None,
    id_map_path: Path | None,
    expected_id_map_path: Path,
    errors: list[str],
) -> None:
    if gold_path is None:
        return

    if id_map_path is None:
        errors.append(f"--gold requires --id-map because model inputs use opaque input_id values")
        errors.append(f"expected an id map like: {expected_id_map_path}")
        return

    try:
        records = load_id_map(id_map_path)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        errors.append(str(exc))
        return

    input_ids = [row.get("input_id") for row in rows if isinstance(row.get("input_id"), str)]
    mapped_input_ids = [record["input_id"] for record in records]
    mapped_sample_ids = [record["sample_id"] for record in records]
    gold_rows = read_jsonl(gold_path)
    gold_ids = [row["sample_id"] for row in gold_rows]

    if len(set(mapped_input_ids)) != len(mapped_input_ids):
        errors.append(f"{id_map_path}: duplicate input_id")
    if len(set(mapped_sample_ids)) != len(mapped_sample_ids):
        errors.append(f"{id_map_path}: duplicate sample_id")
    if set(input_ids) != set(mapped_input_ids):
        missing = sorted(set(input_ids) - set(mapped_input_ids))
        extra = sorted(set(mapped_input_ids) - set(input_ids))
        errors.append(f"{id_map_path}: input ids do not match model input file; missing={missing}, extra={extra}")
    if set(gold_ids) != set(mapped_sample_ids):
        missing = sorted(set(gold_ids) - set(mapped_sample_ids))
        extra = sorted(set(mapped_sample_ids) - set(gold_ids))
        errors.append(f"{id_map_path}: sample ids do not match gold file; missing={missing}, extra={extra}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Check model input JSONL for gold-label leakage.")
    parser.add_argument("inputs", type=Path)
    parser.add_argument("--gold", type=Path, help="Optional gold dataset for sample-id alignment checks.")
    parser.add_argument(
        "--id-map",
        type=Path,
        help="Private input_id -> sample_id map generated by build_model_inputs.py. Defaults to <inputs-stem>.id_map.json when present.",
    )
    args = parser.parse_args()

    rows = read_jsonl(args.inputs)
    errors: list[str] = []
    expected_id_map_path = args.id_map or default_id_map_path(args.inputs)
    id_map_path = expected_id_map_path
    if not expected_id_map_path.exists():
        id_map_path = args.id_map

    for row in rows:
        input_label = row.get("input_id", f"line_{row.get('_line_no', '?')}")
        walk_errors: list[str] = []
        walk_forbidden(row, "", walk_errors)
        for error in walk_errors:
            errors.append(f"{input_label}: {error}")

        check_public_input_id(row, errors)

        task = row.get("task")
        if not isinstance(task, dict) or set(task) != {"description"}:
            errors.append(f"{input_label}: model-facing task must contain only description")

        environment = row.get("environment")
        if not isinstance(environment, dict) or set(environment) != {"source", "content"}:
            errors.append(f"{input_label}: model-facing environment must contain only source and content")

    check_id_map(rows, args.gold, id_map_path, expected_id_map_path, errors)

    if errors:
        print(f"Input check failed with {len(errors)} error(s):")
        for error in errors:
            print(f"- {error}")
        return 1

    print(f"Input check passed: {args.inputs}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
